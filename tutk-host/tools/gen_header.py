#!/usr/bin/env python3
"""Write the headers in include/ from the C blocks of the TUTK kit's docs.

    gen_header.py KIT_DIR [OUT_DIR]

KIT_DIR is the kit root (the directory holding docs/). The headers are generated, not edited: fix the
kit and regenerate.

- tutk_shared.h: the error enums and cross-library types (docs/shared/);
- iotc_types.h, av_types.h: each library's own types (docs/iotc/01-types.md, docs/av/01-types.md).
"""
import pathlib
import re
import sys

# OpenSSL's opaque handles, as OpenSSL declares them; the kit's structs only hold pointers to them.
OSSL_TYPES = "typedef struct ssl_st SSL;\ntypedef struct ssl_ctx_st SSL_CTX;\n"

# name: (docs, includes, declarations before the kit's blocks)
HEADERS = {
    "tutk_shared.h": (("docs/shared/10-errors.md", "docs/shared/20-types.md"),
                      ("<stdint.h>", "<netinet/in.h>"), ""),
    "iotc_types.h": (("docs/iotc/01-types.md",), ("<pthread.h>", '"tutk_shared.h"'), OSSL_TYPES),
    "av_types.h": (("docs/av/01-types.md",), ("<pthread.h>", '"tutk_shared.h"'), ""),
}


def header(kit, name, docs, includes, prelude):
    guard = name.upper().replace(".", "_")
    parts = [f"/* Generated by tools/gen_header.py from the TUTK kit's docs; do not edit. */\n"
             f"#ifndef {guard}\n#define {guard}\n\n"]
    parts += [f"#include {i}\n" for i in includes]
    parts.append("\n")
    if prelude:
        parts.append(prelude + "\n")
    for doc in docs:
        text = (kit / doc).read_text()
        parts.append(f"/* ---- {doc} ---- */\n\n")
        for block in re.findall(r"```c\n(.*?)```", text, re.S):
            parts.append(block.rstrip() + "\n\n")
    parts.append("\n#endif\n")
    return "".join(parts)


def main(argv):
    kit = pathlib.Path(argv[1])
    out = pathlib.Path(argv[2]) if len(argv) > 2 else pathlib.Path(__file__).parent.parent / "include"
    for name, spec in HEADERS.items():
        (out / name).write_text(header(kit, name, *spec))


if __name__ == "__main__":
    main(sys.argv)
