/* ---- output ---- */

static void emit(const char *name, const uint8_t *b, int n) {
    printf("%s = ", name);
    for (int i = 0; i < n; i++)
        printf("%02x", b[i]);
    printf("\n");
}

static void emit_pair(const char *base, const uint8_t *wire_b, int n) {
    uint8_t plain[2048];
    char name[96];

    /* The flags byte is itself scrambled: read it from the unscrambled header first. */
    iotc_unscramble(iotc.key, wire_b, plain, n, IOTC_HEADER_LEN);
    iotc_unscramble(iotc.key, wire_b, plain, n, plain[3] & IOTC_FLAG_PE ? IOTC_PE_PREFIX : n);
    snprintf(name, sizeof name, "%s.plain", base);
    emit(name, plain, n);
    snprintf(name, sizeof name, "%s.wire", base);
    emit(name, wire_b, n);
}

static void note(const char *s) { printf("# %s\n", s); }

int main(void) {
    static const uint8_t kit_plain[16] = {4, 3, 2, 1, 8, 7, 6, 5, 0xc, 0xb, 0xa, 9, 0x10, 0xf, 0xe, 0xd};
    static const uint8_t kit_key[16] = {0x44, 0x33, 0x22, 0x11, 0x88, 0x77, 0x66, 0x55,
                                        0xcc, 0xbb, 0xaa, 0x99, 0x00, 0xff, 0xee, 0xdd};
    static const int lens[] = {1, 2, 3, 4, 7, 8, 15, 16, 17, 33, 64, 100};
    uint8_t buf[2048], msg[128], out[128], payload[100];
    IotcSession s;
    uint8_t probe[IOTC_PROBE_LEN], rec[IOTC_RECORD_LEN];
    char name[96];

    printf("# Generated by tools/fixtures/gen_fixtures.c (gen.sh) from tutk-host; do not edit.\n"
           "# Format: '#' comments, 'name = lowercase hex'.\n"
           "# Synthetic inputs, no real credentials:\n"
           "#   UID TESTUID0123456789ABC, authKey ASCII k3yAuth8, token 0102030405060708,\n"
           "#   SDK version 0x040308c8 (tutk-host's TK_SDK_VERSION is 0x04030864; gen.sh builds against a\n"
           "#   patched copy of tk_common.h in a temp directory), IOTC version 0x1d, peer 192.0.2.1:32761\n"
           "#   (address is irrelevant to the bytes), AV account admin, AV password testpass,\n"
           "#   AV login nonce 0x11223344, camera protocol version 0x1b -> login width W = 0x101.\n"
           "#   IOTC scramble message: msg[i] = (i*37+11)&0xff; data payload: bytes 0..99 (i&0xff).\n\n");

    iotc_build_key();
    note("iotc_build_key() with GetLicenseKeyMask failing: the bare constant 'Charlie is the d'");
    emit("iotc.key", iotc.key, 16);
    iotc_scramble(kit_key, kit_plain, out, 16, 16);
    note("iotc_scramble(kit key, kit plain, len 16, prefix 16): the kit's worked example");
    emit("iotc.scramble.kit", out, 16);

    for (int i = 0; i < 128; i++)
        msg[i] = (uint8_t)(i * 37 + 11);
    printf("\n");
    note("iotc_scramble(iotc.key, msg, len N, prefix N) for each N; .in is msg[0..N)");
    for (size_t k = 0; k < sizeof lens / sizeof *lens; k++) {
        int n = lens[k];

        iotc_scramble(iotc.key, msg, out, n, n);
        snprintf(name, sizeof name, "iotc.scramble.len%d.in", n);
        emit(name, msg, n);
        snprintf(name, sizeof name, "iotc.scramble.len%d.out", n);
        emit(name, out, n);
    }
    note("iotc_scramble(iotc.key, msg, len 100, prefix 0x40): partial encryption, bytes 64.. unchanged");
    iotc_scramble(iotc.key, msg, out, 100, IOTC_PE_PREFIX);
    emit("iotc.scramble.pe.len100.out", out, 100);

    /* a session as the connect handshake leaves it */
    memset(&s, 0, sizeof s);
    memcpy(s.uid, "TESTUID0123456789ABC", 20);
    memcpy(s.authkey, "k3yAuth8", 8);
    memcpy(s.token, "\x01\x02\x03\x04\x05\x06\x07\x08", 8);
    strcpy(s.peer_host, "192.0.2.1");
    s.peer_port = 32761;
    cur_session = &s;
    iotc.conn = &fake_conn;

    printf("\n");
    iotc_build_connect_probe(&s, probe);
    note("iotc_build_connect_probe(): the builder output, flags 0, before iotc_send_to_peer sets FLAG_SCRAMBLED");
    emit("iotc.probe.built", probe, IOTC_PROBE_LEN);
    iotc_build_lan_record(&s, rec);
    note("iotc_build_lan_record(): 52 bytes, never scrambled, HMAC-SHA1 keyed by UID(20, NUL-padded) || authKey");
    emit("iotc.record", rec, IOTC_RECORD_LEN);

    /* iotc_send_connect_request sends the probe, then the ack; capture both */
    {
        uint8_t first[IOTC_PROBE_LEN];

        iotc_build_connect_probe(&s, first);
        first[3] |= IOTC_FLAG_SCRAMBLED;
        iotc_scramble(iotc.key, first, first, IOTC_PROBE_LEN, IOTC_PROBE_LEN);
        iotc_send_to_peer(&s, probe, IOTC_PROBE_LEN);
        if (memcmp(first, wire, IOTC_PROBE_LEN) != 0)
            return 1;
        note("iotc_send_to_peer() of the connect probe (the datagram handed to send()); plain = unscrambled");
        emit_pair("iotc.probe", wire, wire_len);
        iotc_send_connect_request(&s);          /* probe, then ack; wire holds the ack */
        note("iotc_send_connect_request(): its second datagram, the 0x0402 connect ack");
        emit_pair("iotc.connect_ack", wire, wire_len);
    }

    for (int i = 0; i < 100; i++)
        payload[i] = (uint8_t)i;
    s.send_seq[0] = 5;
    s.pe_enabled = false;
    IOTC_Session_Write_Data_And_Datatype(0, payload, 100, 0, 1);
    note("IOTC_Session_Write_Data_And_Datatype(channel 0, datatype 1, 100 bytes), send seq 5, PE off");
    emit_pair("iotc.data", wire, wire_len);
    s.pe_enabled = true;
    IOTC_Session_Write_Data_And_Datatype(0, payload, 100, 0, 1);
    note("same call, PE on (flags 0x0b, scrambled over the first 0x40 bytes only), send seq 6");
    emit_pair("iotc.data.pe", wire, wire_len);
    s.pe_enabled = false;

    iotc_send_keepalive(&s);
    note("iotc_send_keepalive(): opcode 0x0427, 24 bytes");
    emit_pair("iotc.keepalive", wire, wire_len);
    iotc_send_close(&s);
    note("iotc_send_close(): opcode 0x0417, 24 bytes (tutk-host sends it three times; the last is recorded)");
    emit_pair("iotc.close", wire, wire_len);

    /* ---- AV ---- */
    {
        AvObj o;
        uint8_t pkt[0x400];
        int len;
        const uint8_t data[8] = {0xde, 0xad, 0xbe, 0xef, 0x00, 0x01, 0x02, 0x03};

        memset(&o, 0, sizeof o);
        pthread_mutex_init(&o.lock, NULL);
        o.nonce = 0x11223344;

        printf("\n");
        len = build_login(&o, 0, 0x101, "admin", "testpass", 0, 1, pkt);
        note("build_login(nonce 0x11223344, n 0, W 0x101, account admin, password testpass, cred mode 0, hs 1)");
        emit("av.login1", pkt, len);
        len = build_login(&o, 1, 0x101, "admin", "testpass", 0, 1, pkt);
        note("build_login(..., n 1): nonce+1, sub-type 0x20, 2 bytes longer");
        emit("av.login2", pkt, len);

        /* ACK: pn_cum 0x0010, pn_high 0x0014, ctrl_in 0x0003, ack_seq 7, urgent 0, clock 0x12345678,
         * counter 0x0200; the 2-NAK variant has the list {3, 5} and urgent 1 */
        o.pn_cum = 0x0010;
        o.pn_high = 0x0014;
        o.ctrl_in = 0x0003;
        o.ack_seq = 7;
        o.tx_counter = 0x0200;
        o.nak_ms = 0;
        fake_now = 0x12345678;
        send_ack(&o, fake_now);
        note("send_ack(): pn_cum 0x10, pn_high 0x14, ctrl_in 3, ack_seq 7, urgent 0, now 0x12345678 (low 16 bits 0x5678), tx counter 0x0200, no NAKs");
        emit("av.ack", av_wire, av_wire_len);
        nak_list[0] = 3;
        nak_list[1] = 5;
        nak_count = 2;
        o.ack_urgent = true;
        o.nak_ms = 0;
        send_ack(&o, fake_now);
        note("send_ack() again: ack_seq 8, urgent 1, NAK list {3, 5} (offsets from pn_cum as the stub returns them), tx counter 0x0201");
        emit("av.ack.nak", av_wire, av_wire_len);
        nak_count = 0;

        o.rtt_ms = 0x002a;
        o.tx_counter = 0x0300;
        send_report(&o);
        note("send_report(): now 0x12345678, rtt_ms 0x002a, tx counter 0x0300");
        emit("av.report", av_wire, av_wire_len);
        o.tx_counter = 0x0400;
        send_rtt(&o, 0xbeef);
        note("send_rtt(echo 0xbeef): rtt_ms 0x002a at +0x0a and +0x0c; class 0x0b is not counter-stamped");
        emit("av.rtt", av_wire, av_wire_len);

        o.tx_counter = 0x0500;
        o.ctrl_next = 0x0005;
        av_ctrl_send(&o, CTRL_USER, 0x330, data, 8, NULL);
        note("av_ctrl_send(class 0x70 user, type 0x330, payload de ad be ef 00 01 02 03): frame number 5, tx counter 0x0500");
        emit("av.ctrl_frame", av_wire, av_wire_len);
        o.tx_counter = 0x0501;
        av_ctrl_send(&o, CTRL_INTERNAL, OP_RESET, "\x09\x00", 2, NULL);
        note("av_ctrl_send(class 0x10 internal, type 0x24 reset, payload 09 00): frame number 6, tx counter 0x0501");
        emit("av.ctrl_frame.internal", av_wire, av_wire_len);
    }
    return 0;
}
