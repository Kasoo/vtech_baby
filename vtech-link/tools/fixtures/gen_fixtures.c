/* Known-answer wire fixtures from tutk-host, for the vtech-link codec tests. Prints the fixture file
 * (core/tests/fixtures/tutk_host.txt) on stdout: the IOTC scramble, key, probe, record, connect ack, data,
 * keepalive and close datagrams, and the AV login, ACK, report, RTT and control-frame packets.
 *
 * It links iotc/wire.c, handshake.c and data.c as they are, with a fake UDP connection that records the
 * datagram handed to send(), and #includes av/session.c, transport.c and ioctrl.c so their static
 * builders can be called, with a fake AV channel that records the packet handed to the DTLS layer and a
 * fixed clock. Every input is synthetic and fixed; nothing is random.
 *
 * "plain" is the buffer at the moment iotc_send_to_peer scrambles it (so its flags byte already has
 * FLAG_SCRAMBLED), recovered by iotc_unscramble() on the recorded wire bytes. */
#include <openssl/hmac.h>
#include <stdio.h>
#include <string.h>

#define av_now_ms av_now_ms_real      /* session.c defines the real clock; the fixed one replaces it */
#include "av.h"
#include "iotc.h"

/* ---- stubs for what the linked sources need ---- */

IotcState iotc;

int GetLicenseKeyMask(uint8_t *out, int size) { return -1; }

int TUTK3rdSHA1HMAC(const void *key, int key_len, const void *data, int data_len, uint8_t *out,
                    unsigned int out_size) {
    unsigned int n = 0;

    return HMAC(EVP_sha1(), key, key_len, data, (size_t)data_len, out, &n) ? 0 : -1;
}

static IotcSession *cur_session;
int iotc_session_enter(int sid, IotcSession **out) { *out = cur_session; return 0; }
void iotc_unlock(void) {}
void iotc_lock(void) {}

/* The fake UDP connection: remembers the last datagram sent. */
static uint8_t wire[2048];
static int wire_len;
static int fake_send(TConnection *c, const char *host, uint16_t port, const void *data, int *len) {
    memcpy(wire, data, (size_t)*len);
    wire_len = *len;
    return 0;
}
static TConnectionVtbl vtbl = {.send = fake_send};
static TConnection fake_conn = {.vtbl = &vtbl};

/* AV: the fake channel and a fixed clock. */
static uint8_t av_wire[2048];
static int av_wire_len;
int av_chan_write(AvChan *c, const void *buf, int len) {
    memcpy(av_wire, buf, (size_t)len);
    av_wire_len = len;
    return len;
}
int TUTK3rdSHA256(const void *data, int len, uint8_t *out, unsigned int out_size) { return -1; }
static uint32_t fake_now;
static uint16_t nak_list[2];
static int nak_count;
int av_media_naks(AvObj *o, uint16_t *out, int max) {
    memcpy(out, nak_list, sizeof nak_list);
    return nak_count;
}

#include "../../../tutk-host/av/session.c"
#undef av_now_ms
#define av_now_ms av_now_ms_fixed
static uint32_t av_now_ms_fixed(void) { return fake_now; }
#include "../../../tutk-host/av/transport.c"
#include "../../../tutk-host/av/ioctrl.c"
/* transport.c and ioctrl.c reference these; the fixtures never reach them. */
void av_media_on_packet(AvObj *o, const uint8_t *f, int len) {}
void av_fec_on_packet(AvObj *o, const uint8_t *fec, const uint8_t *f, int flen) {}
void av_serv_on_dtls(AvObj *o) {}
void av_serv_on_login(AvObj *o, const uint8_t *p, int len) {}
