#!/usr/bin/env python3
"""Generate the parts of a library that are not written by hand.

    gen_stubs.py IMPORTS DEFINED OUTDIR [--ossl OSSL_H]

IMPORTS is the library's imports.txt. DEFINED lists the symbols the hand-written objects already define
(one per line). Writes into OUTDIR:

- stubs.c: an abort stub for every imported symbol that is neither defined nor a tutk_third_ name.

With --ossl (Global only; OSSL_H is global/ossl.h, whose OSSL_FN lines name the OpenSSL functions Global
calls itself), also:

- ssl_fwd.S: a tail-jump `tutk_third_X` -> `X` for every tutk_third_ import, so the OpenSSL calls
  reach the host's libssl/libcrypto with their arguments untouched;
- ssl_link.c: an empty definition of each OpenSSL function Global forwards or calls, built as the
  link-time stand-in for libssl.so.3 so the NDK link records the dependency.
"""
import argparse
import pathlib
import re
import sys

PREFIX = "tutk_third_"


def main(argv):
    ap = argparse.ArgumentParser()
    ap.add_argument("imports", type=pathlib.Path)
    ap.add_argument("defined", type=pathlib.Path)
    ap.add_argument("out", type=pathlib.Path)
    ap.add_argument("--ossl", type=pathlib.Path)
    a = ap.parse_args(argv[1:])
    imports = a.imports.read_text().split()
    defined = set(a.defined.read_text().split())
    out = a.out
    out.mkdir(parents=True, exist_ok=True)

    ssl = sorted(s[len(PREFIX):] for s in imports if s.startswith(PREFIX))
    stubs = sorted(s for s in imports if not s.startswith(PREFIX) and s not in defined)

    lines = ['/* Generated by tools/gen_stubs.py; do not edit. */', '#include "tk_common.h"', '']
    lines += [f"TK_STUB({s})" for s in stubs]
    (out / "stubs.c").write_text("\n".join(lines) + "\n")
    implemented = sum(1 for s in imports if not s.startswith(PREFIX) and s in defined)
    print(f"{a.imports}: {implemented} implemented, {len(stubs)} stubs", file=sys.stderr)
    if a.ossl is None:
        return
    called = re.findall(r"^OSSL_FN\([^,]+,\s*(\w+)", a.ossl.read_text(), re.M)

    asm = ["/* Generated by tools/gen_stubs.py; do not edit. */",
           "#if defined(__x86_64__)",
           "#define FWD(n) .globl tutk_third_##n; .type tutk_third_##n, @function; "
           "tutk_third_##n: jmp n@PLT",
           "#elif defined(__aarch64__)",
           "#define FWD(n) .globl tutk_third_##n; .type tutk_third_##n, %function; "
           "tutk_third_##n: b n",
           "#else",
           "#error unsupported architecture",
           "#endif",
           "    .text"]
    asm += [f"FWD({s})" for s in ssl]
    asm += ['    .section .note.GNU-stack,"",%progbits']
    (out / "ssl_fwd.S").write_text("\n".join(asm) + "\n")

    link = ["/* Generated by tools/gen_stubs.py; do not edit. */"]
    link += [f"void {s}(void) {{}}" for s in sorted(set(ssl) | set(called))]
    (out / "ssl_link.c").write_text("\n".join(link) + "\n")

    print(f"{len(ssl)} OpenSSL forwarders", file=sys.stderr)


if __name__ == "__main__":
    main(sys.argv)
